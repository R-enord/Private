import { Link } from "react-router-dom";
import { api } from "../lib/api";
import { absoluteTime, compactNumber, metricLabel, relativeTime } from "../lib/format";
import type { ItemCard as Item } from "../lib/types";
import { ExternalLink, LabelBadge, VerificationBadge } from "./ui";

const KIND_ICON: Record<string, string> = {
  repository: "⌥", model: "◈", dataset: "▤", space: "▶", paper: "§", article: "✎", discussion: "💬", release: "⇪",
  opportunity: "★", other: "•",
};

export function ItemCardView({ item, isNew, onChange }: { item: Item; isNew?: boolean; onChange?: (i: Item) => void }) {
  const metrics = Object.entries(item.metrics).filter(([k]) => !["open_issues", "hf_comments"].includes(k)).slice(0, 3);
  const toggleBookmark = async () => {
    const res = await api<{ bookmarked: boolean }>(`/api/items/${item.id}/bookmark`, { method: item.bookmarked ? "DELETE" : "POST" });
    onChange?.({ ...item, bookmarked: res.bookmarked });
  };
  return (
    <article
      className={`rounded-lg border bg-white p-3 shadow-sm transition dark:bg-slate-900 ${isNew ? "border-blue-400 ring-2 ring-blue-200 dark:ring-blue-900" : "border-slate-200 dark:border-slate-800"}`}
    >
      <div className="flex items-start gap-2">
        <span className="mt-0.5 w-5 shrink-0 text-center text-slate-400" title={item.kind} aria-label={item.kind}>
          {KIND_ICON[item.kind] ?? "•"}
        </span>
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-1.5">
            <LabelBadge label={item.label} evidence={item.label_evidence} />
            <VerificationBadge level={item.verification} />
            {item.is_fixture && <span className="rounded bg-yellow-200 px-1 text-xs text-yellow-900">TEST FIXTURE</span>}
            {isNew && <span className="rounded bg-blue-600 px-1 text-xs text-white">new</span>}
          </div>
          <h3 className="mt-1 text-[15px] font-semibold leading-snug">
            <Link to={`/items/${item.id}`} className="hover:underline">
              {item.title}
            </Link>
          </h3>
          {item.summary && <p className="mt-1 line-clamp-2 text-sm text-slate-600 dark:text-slate-400">{item.summary}</p>}
          {item.ai_summary && (
            <p className="mt-1 line-clamp-2 text-sm text-slate-700 dark:text-slate-300">
              <span className="mr-1 rounded bg-slate-200 px-1 text-[10px] font-semibold uppercase text-slate-700 dark:bg-slate-700 dark:text-slate-200" title={`AI-generated by local model ${item.ai_summary.model}; may be imperfect`}>
                AI
              </span>
              {item.ai_summary.summary}
            </p>
          )}
          <div className="mt-2 flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-slate-500">
            <ExternalLink href={item.url}>original ↗</ExternalLink>
            <span title={`Published (per source): ${absoluteTime(item.published_at)}`}>published {relativeTime(item.published_at)}</span>
            <span title={`First seen by this hub: ${absoluteTime(item.discovered_at)}`}>discovered {relativeTime(item.discovered_at)}</span>
            <span>{item.sources.map((s) => s.publisher || s.name).filter((v, i, a) => a.indexOf(v) === i).join(" · ")}</span>
            {metrics.map(([k, v]) => (
              <span key={k} className="tabular-nums">
                {compactNumber(v)} {metricLabel(k)}
              </span>
            ))}
            {item.license && <span title="License as stated by the source">license: {item.license}</span>}
          </div>
          {item.relation && <div className="mt-1 text-xs italic text-slate-500">{item.relation}</div>}
        </div>
        <div className="flex shrink-0 flex-col items-end gap-1">
          <span
            className="rounded bg-slate-100 px-1.5 py-0.5 text-sm font-semibold tabular-nums dark:bg-slate-800"
            title={item.score_reasons.map((r) => `${r.component} +${r.contribution} (${r.kind}): ${r.evidence}`).join("\n")}
          >
            {item.score.toFixed(0)}
          </span>
          <button onClick={toggleBookmark} className="text-lg leading-none text-slate-400 hover:text-amber-500" title={item.bookmarked ? "Remove bookmark" : "Bookmark"} aria-pressed={item.bookmarked}>
            {item.bookmarked ? "★" : "☆"}
          </button>
        </div>
      </div>
    </article>
  );
}

export function ItemList({ items, newIds, onChange }: { items: Item[]; newIds?: Set<number>; onChange?: (i: Item) => void }) {
  return (
    <div className="flex flex-col gap-2">
      {items.map((it) => (
        <ItemCardView key={it.id} item={it} isNew={newIds?.has(it.id)} onChange={onChange} />
      ))}
    </div>
  );
}
